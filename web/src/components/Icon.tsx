export function Icon({
  name,
  size,
  className = "",
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const Glyph = icons[name] || LayoutGrid;
  return (
    <Glyph
      className={`icon ${className}`.trim()}
      aria-hidden="true"
      focusable="false"
      strokeWidth={1.8}
      style={size ? { width: size, height: size } : undefined}
    />
  );
}