#: Permissions the OAuth prompt asks for. Administrator (``permissions=8``) is
#: deliberately not included: Discord's bot review, and top.gg's approval
#: checklist, reject bots that only work when they are invited as an
#: administrator. Every feature has to work with this scoped set instead —
#: Manage Roles covers lock/unlock and role rewards, Manage Channels covers
#: ticket and voice channels, View Audit Log covers anti-nuke and invite
#: tracking, and the rest is ordinary posting and moderation.
#:
#:    view_channel, send_messages, send_messages_in_threads, embed_links,
#:    attach_files, add_reactions, read_message_history,
#:    use_external_emojis, manage_messages, manage_roles, manage_channels,
#:    kick_members, ban_members, moderate_members, manage_webhooks,
#:    view_audit_log, mention_everyone, create_instant_invite,
#:    manage_threads, create_public_threads, create_private_threads,
#:    connect, speak, move_members
BOT_PERMISSIONS = 1_495_474_367_703

OAUTH_SCOPES = "bot applications.commands"


def invite_url(client_id, *, guild_id=None, permissions: int = BOT_PERMISSIONS) -> str:
    """The bot's OAuth invite, scoped to :data:`BOT_PERMISSIONS`.

    ``guild_id`` preselects a server (``guild_id`` OAuth parameter), which is
    what the dashboard's "Add Niko" button on a server card does.
    """
    params = {
        "client_id": client_id,
        "permissions": str(int(permissions)),
        "scope": OAUTH_SCOPES,
    }
    if guild_id is not None:
        params["guild_id"] = guild_id
    return "https://discord.com/oauth2/authorize?" + urlencode(params)


def dashboard_url(guild_id) -> str:
    """The dashboard home for one server."""
    return f"{WEBSITE}/dashboard/{int(guild_id)}"


